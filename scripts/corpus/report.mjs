#!/usr/bin/env node
// Summarizes a corpus run (pairs.jsonl from run.mjs) into summary.json and a Markdown report, including the
// operation-level disagreements with oasdiff that need triage.
//   node scripts/corpus/report.mjs corpus/results/<date> [--md docs/reports/<file>.md]
import { readFileSync, writeFileSync } from 'node:fs';
import { join, resolve } from 'node:path';

const argv = process.argv.slice(2);
const dir = resolve(argv[0] ?? '.');
const mdOut = argv.includes('--md') ? resolve(argv[argv.indexOf('--md') + 1]) : join(dir, 'report.md');
const pairs = readFileSync(join(dir, 'pairs.jsonl'), 'utf8')
  .split('\n')
  .filter(Boolean)
  .map((l) => JSON.parse(l));

const pct = (a, b) => (b === 0 ? '–' : `${((100 * a) / b).toFixed(1)}%`);
const quantile = (xs, q) => {
  const s = [...xs].sort((a, b) => a - b);
  return s.length === 0 ? 0 : s[Math.min(s.length - 1, Math.floor(q * s.length))];
};
const count = (items) => {
  const m = new Map();
  for (const i of items) m.set(i, (m.get(i) ?? 0) + 1);
  return [...m.entries()].sort((a, b) => b[1] - a[1] || (a[0] < b[0] ? -1 : 1));
};

const sources = [...new Set(pairs.map((p) => p.source))];
const compared = pairs.filter((p) => p.onlyCg !== undefined);
const cgOk = pairs.filter((p) => p.cgStatus === 'completed' || p.cgStatus === 'completed-degraded');
const selfChecked = pairs.filter((p) => Array.isArray(p.selfNonInformational));
const selfViolations = selfChecked.filter((p) => p.selfNonInformational.length > 0);
const cls = (p, c) => p.cgFindings.filter((f) => f.cls === c).length;

const summary = {
  pairs: pairs.length,
  sources: sources.length,
  contractguard: {
    completed: cgOk.length,
    inputErrors: count(pairs.filter((p) => p.cgStatus === 'input-error').flatMap((p) => p.cgDiagnostics)),
    findings: Object.fromEntries(
      ['breaking', 'potentially-breaking', 'undetermined', 'non-breaking', 'informational'].map((c) => [
        c,
        pairs.reduce((n, p) => n + cls(p, c), 0),
      ]),
    ),
    pairsWithBreaking: pairs.filter((p) => cls(p, 'breaking') > 0).length,
    msP50: quantile(
      cgOk.map((p) => p.cgMs),
      0.5,
    ),
    msP95: quantile(
      cgOk.map((p) => p.cgMs),
      0.95,
    ),
    msMax: Math.max(0, ...cgOk.map((p) => p.cgMs)),
    rssMaxMb: Math.max(0, ...pairs.map((p) => p.cgRssMb ?? 0)),
  },
  selfComparison: {
    checked: selfChecked.length,
    violations: selfViolations.length,
    samples: selfViolations
      .slice(0, 5)
      .map((p) => ({ source: p.source, commit: p.candidate, findings: p.selfNonInformational.slice(0, 5) })),
  },
  oasdiff: {
    errors: count(pairs.filter((p) => p.oaError !== undefined).map((p) => p.oaError.slice(0, 80))),
    pairsWithBreaking: pairs.filter((p) => (p.oaFindings ?? []).some((f) => f.level === 3)).length,
    msP50: quantile(
      pairs.filter((p) => p.oaMs !== undefined).map((p) => p.oaMs),
      0.5,
    ),
    msP95: quantile(
      pairs.filter((p) => p.oaMs !== undefined).map((p) => p.oaMs),
      0.95,
    ),
  },
  comparison: {
    pairs: compared.length,
    pairsAgreeing: compared.filter((p) => p.onlyCg.length === 0 && p.onlyOasdiff.length === 0).length,
    operationsBoth: compared.reduce((n, p) => n + p.both.length, 0),
    operationsOnlyContractGuard: compared.reduce((n, p) => n + p.onlyCg.length, 0),
    operationsOnlyOasdiff: compared.reduce((n, p) => n + p.onlyOasdiff.length, 0),
    onlyContractGuardRules: count(
      compared.flatMap((p) =>
        p.cgFindings.filter((f) => f.cls === 'breaking' && p.onlyCg.includes(f.op)).map((f) => f.rule),
      ),
    ),
    onlyOasdiffIds: count(
      compared.flatMap((p) =>
        (p.oaFindings ?? []).filter((f) => f.level === 3 && p.onlyOasdiff.includes(f.op)).map((f) => f.id),
      ),
    ),
  },
};
writeFileSync(join(dir, 'summary.json'), `${JSON.stringify(summary, null, 2)}\n`);

// ------------------------------------------------------------------ Markdown
const L = [];
L.push(`# Real-world corpus and differential report`, '');
L.push(
  `${String(pairs.length)} consecutive version pairs from ${String(sources.length)} public API histories, compared with ContractGuard and oasdiff (\`breaking\`). Generated by \`scripts/corpus/report.mjs\`.`,
  '',
);
L.push(
  '## Per source',
  '',
  '| Source | Pairs | ContractGuard completed | CG input errors | Pairs breaking (CG) | Pairs breaking (oasdiff) | Pairs agreeing | CG p95 ms |',
  '|---|---:|---:|---:|---:|---:|---:|---:|',
);
for (const s of sources) {
  const ps = pairs.filter((p) => p.source === s);
  const ok = ps.filter((p) => p.cgStatus !== 'input-error');
  const cmp = ps.filter((p) => p.onlyCg !== undefined);
  L.push(
    `| ${s} | ${String(ps.length)} | ${String(ok.length)} | ${String(ps.length - ok.length)} | ${String(ps.filter((p) => cls(p, 'breaking') > 0).length)} | ${String(ps.filter((p) => (p.oaFindings ?? []).some((f) => f.level === 3)).length)} | ${String(cmp.filter((p) => p.onlyCg.length === 0 && p.onlyOasdiff.length === 0).length)}/${String(cmp.length)} | ${String(
      quantile(
        ok.map((p) => p.cgMs),
        0.95,
      ),
    )} |`,
  );
}
L.push('');
L.push('## Success metrics (§2.9)', '');
L.push(
  `- **Self-comparison** (\`check(A, A)\` on two independent loads): ${String(summary.selfComparison.violations)} of ${String(summary.selfComparison.checked)} versions produced a non-informational finding.`,
);
L.push(`- **Differential coverage**: ${String(compared.length)} pairs compared with oasdiff (target ≥ 500).`);
L.push(
  `- **Performance**: ContractGuard p50 ${String(summary.contractguard.msP50)} ms, p95 ${String(summary.contractguard.msP95)} ms, max ${String(summary.contractguard.msMax)} ms per pair; peak RSS ${String(summary.contractguard.rssMaxMb)} MB.`,
  '',
);
L.push('## Agreement on breaking operations', '');
L.push(
  `An operation counts as breaking for a tool when the tool reports a breaking finding (ContractGuard) or an \`ERR\` (oasdiff) for it. Findings without an operation (servers, global security, components) count as \`(global)\`.`,
  '',
);
L.push(`| | Operations |`, `|---|---:|`);
L.push(`| Breaking in both | ${String(summary.comparison.operationsBoth)} |`);
L.push(`| Breaking only in ContractGuard | ${String(summary.comparison.operationsOnlyContractGuard)} |`);
L.push(`| Breaking only in oasdiff | ${String(summary.comparison.operationsOnlyOasdiff)} |`);
L.push(
  `| Pairs with identical verdicts | ${String(summary.comparison.pairsAgreeing)} of ${String(compared.length)} (${pct(summary.comparison.pairsAgreeing, compared.length)}) |`,
  '',
);
L.push(
  '### Rules behind ContractGuard-only operations',
  '',
  '| Rule | Operations |',
  '|---|---:|',
  ...summary.comparison.onlyContractGuardRules.slice(0, 15).map(([r, n]) => `| ${r} | ${String(n)} |`),
  '',
);
L.push(
  '### oasdiff checks behind oasdiff-only operations',
  '',
  '| oasdiff id | Operations |',
  '|---|---:|',
  ...summary.comparison.onlyOasdiffIds.slice(0, 15).map(([r, n]) => `| \`${r}\` | ${String(n)} |`),
  '',
);
L.push(
  '## ContractGuard input errors',
  '',
  ...(summary.contractguard.inputErrors.length === 0
    ? ['None.']
    : [
        '| Diagnostic | Pairs |',
        '|---|---:|',
        ...summary.contractguard.inputErrors.map(([c, n]) => `| ${c} | ${String(n)} |`),
      ]),
  '',
);
writeFileSync(mdOut, `${L.join('\n')}\n`);
console.log(`Wrote ${join(dir, 'summary.json')} and ${mdOut}`);
