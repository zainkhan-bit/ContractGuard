#!/usr/bin/env node
// Generates the reference pages of the docs site from the code, so docs cannot drift (R15):
//   docs/rules/*.md        one page per rule: metadata from the catalog + examples from the executed fixtures
//   docs/rules/index.md    the catalog
//   docs/reference/cli.md  every command's --help
//   docs/reference/config.md  every key of .contractguard.yaml from the JSON Schema
//   docs/.vitepress/rules-sidebar.json
// Run after `pnpm build`. CI regenerates and fails when the committed pages differ.
import { mkdirSync, readdirSync, rmSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

const root = join(import.meta.dirname, '..');
const dist = (pkg) => join(root, 'packages', pkg, 'dist', 'index.js');
const core = await import(dist('core'));
const openapi = await import(dist('openapi'));
const engine = await import(dist('engine'));
const app = await import(dist('app'));
const cli = await import(dist('cli'));
// Fixtures are TypeScript with type-only imports; Node strips the types.
const { FIXTURES } = await import(join(root, 'packages/engine/test/compat/fixtures.ts'));

const docs = join(root, 'docs');
const AREA = {
  API: ['Operations and paths', 'Operations, paths and methods that consumers call.'],
  SRV: ['Servers', 'Where the API is served.'],
  REQ: ['Requests', 'What consumers send: parameters, headers, bodies.'],
  RES: ['Responses', 'What consumers receive: status codes, headers, bodies.'],
  SCHEMA: ['Schemas', 'Schema-level changes that are not tied to one direction.'],
  AUTH: ['Security', 'Security schemes, scopes and requirements.'],
};
const AREAS = Object.keys(AREA);

// ------------------------------------------------------------------ running fixtures

const POLICY = {
  root: '/',
  allowRemote: false,
  allowedHosts: [],
  allowedSchemes: ['https'],
  fetchTimeoutMs: 1000,
  maxRemoteBytes: 1,
};
const ROOT = core.documentUri('file:///api/openapi.yaml');

async function load(text) {
  const loader = new openapi.MemorySourceLoader([[ROOT, text]], ['file:']);
  const r = await openapi.loadContract(ROOT, {
    loader,
    policy: POLICY,
    limits: core.DEFAULT_LIMITS,
    validator: false,
    allowInvalidSpec: true,
  });
  return r.value?.contract;
}

/** Lenient loading, as the engine tests do for fixtures with unresolved references. */
async function lenient(text) {
  const loader = new openapi.MemorySourceLoader([[ROOT, text]], ['file:']);
  const ctx = { policy: POLICY, limits: core.DEFAULT_LIMITS };
  const loaded = await loader.load(ROOT, ctx);
  const doc = openapi.parseDocument(loaded.value, { limits: core.DEFAULT_LIMITS }).value;
  const version = openapi.detectVersion(doc).value;
  const set = await openapi.resolveReferences(doc, version.dialect, { loader, ctx });
  return openapi.normalize(set.value, version, { limits: core.DEFAULT_LIMITS }).value;
}

async function findingsOf(fx) {
  const read = fx.lenient === true ? lenient : load;
  const [b, c] = [await read(fx.base), await read(fx.candidate)];
  if (b === undefined || c === undefined) return undefined;
  return engine.checkCompatibility(b, c, fx.options).findings.filter((f) => f.ruleId === fx.rule);
}

// ------------------------------------------------------------------ helpers

/** Minimal line diff (LCS) rendered as a ```diff block. */
function lineDiff(a, b) {
  const x = a.replace(/\n$/, '').split('\n');
  const y = b.replace(/\n$/, '').split('\n');
  const n = x.length;
  const m = y.length;
  const lcs = Array.from({ length: n + 1 }, () => new Array(m + 1).fill(0));
  for (let i = n - 1; i >= 0; i--)
    for (let j = m - 1; j >= 0; j--)
      lcs[i][j] = x[i] === y[j] ? lcs[i + 1][j + 1] + 1 : Math.max(lcs[i + 1][j], lcs[i][j + 1]);
  const out = [];
  let i = 0;
  let j = 0;
  while (i < n || j < m) {
    if (i < n && j < m && x[i] === y[j]) {
      out.push(`  ${x[i++]}`);
      j++;
    } else if (i < n && (j === m || lcs[i + 1][j] >= lcs[i][j + 1])) out.push(`- ${x[i++]}`);
    else out.push(`+ ${y[j++]}`);
  }
  return out.join('\n');
}

const esc = (s) => String(s).replace(/\|/g, '\\|').replace(/</g, '&lt;').replace(/\{\{/g, '&#123;&#123;');
const CLASS = {
  breaking: 'Breaking',
  'potentially-breaking': 'Potentially breaking',
  undetermined: 'Undetermined',
  'non-breaking': 'Non-breaking',
  informational: 'Informational',
};

function write(rel, text) {
  const file = join(docs, rel);
  mkdirSync(join(file, '..'), { recursive: true });
  writeFileSync(file, `${text.trimEnd()}\n`);
}

const GENERATED =
  '<!-- Generated by scripts/generate-docs.mjs from the rule catalog and fixtures. Do not edit. -->\n\n';

// ------------------------------------------------------------------ rule pages

rmSync(join(docs, 'rules'), { recursive: true, force: true });
const missing = [];
const rules = engine.RULES.map((r) => engine.explainRule(r.id));
for (const e of rules) {
  const fixtures = FIXTURES.filter((f) => f.rule === e.id);
  const lines = [GENERATED, `# ${e.id}: ${e.name}`, '', e.summary, '', `**Why it matters:** ${e.rationale}`, ''];
  lines.push('| Attribute | Value |', '|---|---|');
  lines.push(`| Area | [${AREA[e.area][0]}](./#${e.area.toLowerCase()}) |`);
  if (e.direction !== undefined) lines.push(`| Direction | ${e.direction} |`);
  lines.push(`| Detects | ${e.handles.map((h) => `\`${h}\``).join(', ')} |`);
  lines.push(
    `| Severity | breaking: ${e.severityProfile.breaking} · potentially breaking: ${e.severityProfile.potentiallyBreaking} · undetermined: ${e.severityProfile.undetermined} |`,
  );
  lines.push(
    `| Classification can be overridden | ${e.overridable.classification ? 'yes' : 'no (the rule only fires when the change is breaking by definition)'} |`,
  );
  lines.push('');
  lines.push(
    '## Message',
    '',
    `> ${esc(e.messages.message)}`,
    '>',
    `> ${esc(e.messages.explanation)}`,
    '>',
    `> **Fix:** ${esc(e.messages.resolution)}`,
    '',
  );
  if (e.options.length > 0) {
    lines.push(
      '## Options',
      '',
      'Set in `.contractguard.yaml` under `rules.overrides.' + e.id + '.options`.',
      '',
      '| Option | Type | Default | Meaning |',
      '|---|---|---|---|',
    );
    for (const o of e.options)
      lines.push(`| \`${o.name}\` | ${o.type} | \`${String(o.default)}\` | ${esc(o.description)} |`);
    lines.push('');
  }
  if (fixtures.length > 0) {
    lines.push(
      '## Examples',
      '',
      'Each example is an executed test case of the rule (`packages/engine/test/compat/fixtures.ts`).',
      '',
    );
    const shown = [...fixtures.filter((f) => f.fires).slice(0, 3), ...fixtures.filter((f) => !f.fires).slice(0, 2)];
    for (const fx of shown) {
      const found = await findingsOf(fx);
      lines.push(`### ${fx.fires ? 'Fires' : 'Does not fire'}: ${esc(fx.name)}`, '');
      if (fx.options !== undefined && Object.keys(fx.options).length > 0)
        lines.push(
          `With options: \`${JSON.stringify(fx.options, (k, v) => (v instanceof Map ? Object.fromEntries(v) : v instanceof Set ? [...v] : v))}\``,
          '',
        );
      lines.push('```diff', lineDiff(fx.base, fx.candidate), '```', '');
      if (fx.fires && found !== undefined && found.length > 0) {
        const f = found[0];
        lines.push(`**Result:** ${CLASS[f.classification]}, ${f.severity}. ${esc(f.message)}`, '');
      } else if (fx.fires) {
        missing.push(`${fx.rule}: ${fx.name}`);
      } else {
        lines.push('**Result:** no finding from this rule.', '');
      }
    }
  }
  if (e.limitations.length > 0) {
    lines.push('## Limitations', '', ...e.limitations.map((l) => `- ${esc(l)}`), '');
  }
  lines.push(
    '## Silence or tune it',
    '',
    '```yaml',
    'rules:',
    '  ignore:',
    `    - rule: ${e.id}`,
    '      operation: "GET /example"   # optional: narrow it down',
    '      reason: "Explain why this is acceptable"',
    '      expires: 2027-01-01         # optional',
    ...(e.overridable.severity ? ['  overrides:', `    ${e.id}: { severity: low }`] : []),
    '```',
  );
  write(`rules/${e.id}.md`, lines.join('\n'));
}

// ------------------------------------------------------------------ catalog index

{
  const lines = [
    GENERATED,
    '# Rules',
    '',
    `ContractGuard ${engine.RULESET_VERSION} has **${rules.length} rules**. Each finding names its rule, so \`contractguard explain <rule-id>\` or the pages below tell you exactly what was detected and why.`,
    '',
  ];
  lines.push(
    "A rule decides the **classification** of a change from the compatibility perspective (default: *provider-backward*: can existing consumers keep working?). The severity follows from the classification and the rule's severity profile. See [Classification and severity](/concepts/classification).",
    '',
  );
  for (const a of AREAS) {
    const list = rules.filter((r) => r.area === a);
    lines.push(
      `## ${AREA[a][0]} {#${a.toLowerCase()}}`,
      '',
      `${AREA[a][1]} ${list.length} rules.`,
      '',
      '| Rule | Name | Detects |',
      '|---|---|---|',
    );
    for (const r of list) lines.push(`| [${r.id}](./${r.id}) | ${esc(r.name)} | ${esc(r.summary)} |`);
    lines.push('');
  }
  write('rules/index.md', lines.join('\n'));
  const sidebar = AREAS.map((a) => ({
    text: AREA[a][0],
    collapsed: true,
    items: rules.filter((r) => r.area === a).map((r) => ({ text: r.id, link: `/rules/${r.id}` })),
  }));
  mkdirSync(join(docs, '.vitepress'), { recursive: true });
  writeFileSync(join(docs, '.vitepress', 'rules-sidebar.json'), `${JSON.stringify(sidebar, null, 2)}\n`);
}

// ------------------------------------------------------------------ CLI reference

async function help(args) {
  let out = '';
  await cli.run(args, {
    stdout: { write: (t) => (out += t) },
    stderr: { write: () => undefined },
    env: {},
    cwd: root,
    today: '2026-01-01',
    readStdin: () => Promise.resolve(''),
  });
  return out.replace(/^ContractGuard \d+\.\d+\.\d+\S*/m, 'ContractGuard');
}

{
  const lines = [GENERATED, '# CLI reference', '', '```text', (await help(['--help'])).trimEnd(), '```', ''];
  for (const [title, args] of [
    ['check', ['check', '--help']],
    ['validate', ['validate', '--help']],
    ['explain', ['explain', '--help']],
    ['baseline create', ['baseline', 'create', '--help']],
    ['init', ['init', '--help']],
  ]) {
    lines.push(`## ${title}`, '', '```text', (await help(args)).trimEnd(), '```', '');
  }
  lines.push('## Sources', '', '| Form | Meaning |', '|---|---|');
  lines.push('| `openapi.yaml` | A file in the working tree |');
  lines.push(
    '| `git:<ref>:<path>` | The file at a git revision, e.g. `git:origin/main:api/openapi.yaml`. Relative `$ref`s resolve in the same commit. The path is relative to the current directory. |',
  );
  lines.push(
    "| `git:@base:<path>` | The file at the base revision: the GitHub Action's base commit, or `--base-ref` |",
  );
  lines.push('| `snapshot:<file>` | A snapshot written by `contractguard baseline create` (checksummed) |');
  lines.push('| `https://…` | A remote document; only when allowed (`references.allowRemote`) |');
  lines.push('| `-` | Standard input (candidate only, self-contained) |', '');
  lines.push(
    '## Exit codes',
    '',
    '| Code | Meaning |',
    '|---|---|',
    '| 0 | Analysis completed and the policy passed (or `--no-fail`) |',
    '| 1 | Analysis completed and the policy failed |',
    '| 2 | Invalid input: a specification could not be loaded, parsed or validated |',
    '| 3 | Usage or configuration error |',
    '| 4 | Internal error (please report it) |',
    '| 130 | Interrupted (Ctrl+C) |',
    '',
  );
  lines.push(
    '## Environment variables',
    '',
    '| Variable | Effect |',
    '|---|---|',
    '| `CI=true` | CI mode: no colour, JSON report files, trust rules for remote references |',
    '| `NO_COLOR` / `FORCE_COLOR` | Disable / force coloured output |',
    '| `CONTRACTGUARD_CONFIG` | Configuration file to use |',
    '| `CONTRACTGUARD_LOG_LEVEL` | `quiet`, `verbose` or `debug` |',
  );
  write('reference/cli.md', lines.join('\n'));
}

// ------------------------------------------------------------------ configuration reference

{
  const schema = app.configJsonSchema();
  const SECTION = {
    specs: 'The comparisons to run.',
    compatibility: 'The compatibility model.',
    policy: 'When the check fails.',
    analysis: 'How changes are classified, and resource limits.',
    rules: 'Turn rules off, change their classification or severity, or silence specific findings.',
    filters: 'Which operations are checked.',
    references: 'Where `$ref` may point. Remote references are off by default.',
    report: 'Report formats and files.',
    'analysis.limits':
      'Resource limits; inputs above them are rejected or reported as undetermined, never silently passed.',
    'rules.overrides':
      'Per-rule settings keyed by rule id: `classification` (when the rule allows it), `severity`, `options`.',
    'rules.ignore':
      'Accepted findings. Each entry needs `rule` or `fingerprint` and a `reason`; suppressed findings stay visible in reports.',
  };
  const rows = [];
  const typeOf = (n) => {
    if (n === undefined) return '';
    if (n.enum !== undefined) return n.enum.map((v) => `\`${v}\``).join(', ');
    if (n.const !== undefined) return `\`${n.const}\``;
    if (n.type === 'array') return `list of ${typeOf(n.items) || 'items'}`;
    if (n.anyOf !== undefined) return n.anyOf.map(typeOf).filter(Boolean).join(' or ');
    if (n.type === 'object' && n.additionalProperties !== undefined && n.properties === undefined) return 'map';
    return n.type ?? '';
  };
  const walk = (node, path) => {
    if (node === undefined || typeof node !== 'object') return;
    const props = node.properties ?? node.items?.properties;
    if (props === undefined) return;
    for (const [k, v] of Object.entries(props)) {
      const p = `${path}${path === '' ? '' : node.items === undefined ? '.' : '[].'}${k}`;
      const t = v.type === 'object' && v.properties !== undefined ? 'object' : typeOf(v);
      rows.push(`| \`${p}\` | ${esc(t)} | ${esc(v.description ?? SECTION[p] ?? '')} |`);
      walk(v, p);
    }
  };
  walk(schema, '');
  const lines = [
    GENERATED,
    '# Configuration reference',
    '',
    '`.contractguard.yaml` (or `.yml`, `.json`) is found in the current directory or a parent, up to the git root. Unknown keys are errors, reported with the file, line and column. Paths are relative to the configuration file.',
    '',
    'Editors with YAML language support validate and complete the file with the published schema:',
    '',
    '```yaml',
    '# yaml-language-server: $schema=./node_modules/@zainkhan-bit/contractguard-app/schemas/config.v1.json',
    'version: 1',
    '```',
    '',
    '| Key | Type | Meaning |',
    '|---|---|---|',
    ...rows,
    '',
    'Sizes accept `512KB`, `20MB`, `1GB` (binary units; `MiB` spellings too) or a number of bytes.',
  ];
  write('reference/config.md', lines.join('\n'));
}

const count = readdirSync(join(docs, 'rules')).length;
if (missing.length > 0) {
  console.error(`Fixtures that should fire produced no finding:\n${missing.join('\n')}`);
  process.exit(1);
}
console.log(`docs: ${String(count)} rule pages, CLI and configuration reference`);
